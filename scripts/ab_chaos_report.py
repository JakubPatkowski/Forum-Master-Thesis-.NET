#!/usr/bin/env python3
"""Error/latency timeline around injected faults (scripts/ab-chaos.sh) → timeline.json + CHAOS-REPORT.md.

Inputs (one chaos run directory):
  k6-points-*.csv.gz   every k6 metric point (K6_OUT=csv=…); only http_req_duration / http_req_failed /
                       forum_ws_* rows are used, bucketed per BUCKET_S seconds of wall-clock time
  faults.json          [{"fault": "pod-crash"|"pod-delete"|"db-restart", "at_epoch": …, "detail": "…"}]
  journeys-*.json      the summary block (window, ws probe loss, totals)

Per bucket: requests, failed, failed %, p95 ms. Per fault: the first bucket with failures after the fault, the
number of failed requests attributable to it (until the first clean bucket), and the recovery time = seconds from
the fault until 3 consecutive clean buckets (no failures AND p95 ≤ 2 × the pre-fault baseline p95).
"""
import csv
import glob
import gzip
import json
import os
import statistics
import sys

BUCKET_S = 5


def pct(values, q):
    if not values:
        return None
    values = sorted(values)
    k = max(0, min(len(values) - 1, int(round(q * (len(values) - 1)))))
    return values[k]


def load_points(run_dir):
    files = sorted(glob.glob(os.path.join(run_dir, "k6-points-*.csv.gz")) + glob.glob(os.path.join(run_dir, "k6-points-*.csv")))
    if not files:
        sys.exit(f"no k6-points-*.csv[.gz] in {run_dir}")
    buckets = {}
    ws_events = []
    opener = gzip.open if files[-1].endswith(".gz") else open
    with opener(files[-1], "rt", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            name = row.get("metric_name")
            if name not in ("http_req_duration", "http_req_failed", "forum_ws_errors", "forum_ws_probes_lost"):
                continue
            # Only the measured http scenario (setup logins / pool crawl carry no scenario tag; the ws scenario's
            # own http calls are the probe writes — excluded from the request timeline, counted via the ws metrics).
            if name.startswith("http") and row.get("scenario") != "http":
                continue
            ts = int(float(row["timestamp"]))
            b = buckets.setdefault(ts - ts % BUCKET_S, {"requests": 0, "failed": 0, "durations": []})
            if name == "http_req_duration":
                b["requests"] += 1
                b["durations"].append(float(row["metric_value"]))
            elif name == "http_req_failed":
                b["failed"] += int(float(row["metric_value"]) >= 1)
            else:
                ws_events.append({"at_epoch": ts, "metric": name})
    out = []
    for start in sorted(buckets):
        b = buckets[start]
        out.append({"start_epoch": start, "requests": b["requests"], "failed": b["failed"],
                    "failed_pct": round(100.0 * b["failed"] / b["requests"], 2) if b["requests"] else None,
                    "p95_ms": round(pct(b["durations"], 0.95), 1) if b["durations"] else None})
    return out, ws_events


def analyse(buckets, faults, window):
    start = window["start_ms"] / 1000.0 if window else buckets[0]["start_epoch"]
    first_fault = min((f["at_epoch"] for f in faults), default=None)
    baseline = [b["p95_ms"] for b in buckets if b["p95_ms"] is not None and b["start_epoch"] >= start
                and (first_fault is None or b["start_epoch"] + BUCKET_S <= first_fault)]
    base_p95 = statistics.median(baseline) if baseline else None
    results = []
    for f in faults:
        after = [b for b in buckets if b["start_epoch"] + BUCKET_S > f["at_epoch"]]
        failed_total = 0
        first_failure = None
        recovered_at = None
        clean_run = 0
        for b in after:
            clean = b["failed"] == 0 and (base_p95 is None or b["p95_ms"] is None or b["p95_ms"] <= 2 * base_p95)
            if b["failed"] and first_failure is None:
                first_failure = b["start_epoch"]
            if not clean:
                failed_total += b["failed"]
                clean_run = 0
            else:
                clean_run += 1
                if clean_run == 3 and (first_failure is not None or b["start_epoch"] >= f["at_epoch"] + BUCKET_S):
                    recovered_at = b["start_epoch"] - 2 * BUCKET_S
                    break
        results.append({**f, "baseline_p95_ms": base_p95, "first_failure_epoch": first_failure,
                        "failed_requests": failed_total,
                        "recovery_s": (recovered_at - f["at_epoch"]) if recovered_at is not None else None,
                        "max_p95_ms_after": max((b["p95_ms"] or 0) for b in after[: 24]) if after else None})
    return base_p95, results


def report(run_dir, buckets, faults_out, base_p95, jdoc, ws_events):
    md = [f"# Chaos run `{os.path.basename(run_dir)}`", "",
          f"Generated by `scripts/ab_chaos_report.py` from the k6 point stream (buckets of {BUCKET_S} s). "
          f"Baseline p95 (pre-fault buckets): {base_p95 if base_p95 is not None else '–'} ms.", ""]
    md.append("| fault | at (UTC) | detail | first failure after | failed requests | recovery (s) | max p95 after (ms) |")
    md.append("|---|---|---|---|---|---|---|")
    import datetime
    for f in faults_out:
        at = datetime.datetime.utcfromtimestamp(f["at_epoch"]).strftime("%H:%M:%S")
        ff = f"{f['first_failure_epoch'] - f['at_epoch']:+d} s" if f["first_failure_epoch"] is not None else "none"
        md.append(f"| {f['fault']} | {at} | {f.get('detail', '')} | {ff} | {f['failed_requests']} | "
                  f"{f['recovery_s'] if f['recovery_s'] is not None else 'not within the run'} | {f['max_p95_ms_after'] or '–'} |")
    md.append("")
    tot = (jdoc or {}).get("totals", {})
    ws = tot.get("ws", {})
    md.append(f"Run totals: {tot.get('http_reqs')} requests, {tot.get('http_req_failed_pct')} % failed, journey p95 "
              f"{(tot.get('journey_duration_ms') or {}).get('p95')} ms; WS errors {ws.get('errors')}, probe loss "
              f"{ws.get('probe_loss_pct')} % ({ws.get('probes_lost')} of {ws.get('probes_sent')}), receipt p95 "
              f"{(ws.get('receipt_ms') or {}).get('p95')} ms; WS error/loss events during the run: {len(ws_events)}.")
    md.append("")
    md.append("## Timeline (5-s buckets with failures or a p95 above 2× baseline)")
    md.append("| t (UTC) | requests | failed | failed % | p95 ms |")
    md.append("|---|---|---|---|---|")
    for b in buckets:
        hot = b["failed"] or (base_p95 and b["p95_ms"] and b["p95_ms"] > 2 * base_p95)
        if hot:
            md.append(f"| {datetime.datetime.utcfromtimestamp(b['start_epoch']).strftime('%H:%M:%S')} | {b['requests']} | "
                      f"{b['failed']} | {b['failed_pct']} | {b['p95_ms']} |")
    return "\n".join(md) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    run_dir = os.path.abspath(sys.argv[1])
    faults = json.load(open(os.path.join(run_dir, "faults.json"))) if os.path.exists(os.path.join(run_dir, "faults.json")) else []
    jfiles = sorted(glob.glob(os.path.join(run_dir, "journeys-*.json")))
    jdoc = json.load(open(jfiles[-1])) if jfiles else None
    buckets, ws_events = load_points(run_dir)
    base_p95, faults_out = analyse(buckets, faults, (jdoc or {}).get("window"))
    json.dump({"bucket_s": BUCKET_S, "baseline_p95_ms": base_p95, "faults": faults_out, "buckets": buckets,
               "ws_events": ws_events}, open(os.path.join(run_dir, "timeline.json"), "w"), indent=1)
    open(os.path.join(run_dir, "CHAOS-REPORT.md"), "w").write(report(run_dir, buckets, faults_out, base_p95, jdoc, ws_events))
    for f in faults_out:
        print(f"  {f['fault']}: failed={f['failed_requests']} recovery={f['recovery_s']}s max_p95={f['max_p95_ms_after']}")


if __name__ == "__main__":
    main()
